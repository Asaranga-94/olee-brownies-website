function getProductById(id) {
    return products.find(product => product.id === id);
}

function createCatalogCard(product) {
    const card = document.createElement("a");
    card.className = "catalog-card";
    card.href = `product.html?id=${encodeURIComponent(product.id)}`;
    card.setAttribute("aria-label", `View ${product.name}`);

    const image = document.createElement("img");
    image.className = "catalog-card-image";
    image.src = product.images[0];
    image.alt = product.name;
    image.loading = "lazy";

    const name = document.createElement("h3");
    name.className = "catalog-card-name";
    name.textContent = product.name;

    card.append(image, name);
    return card;
}

function renderProductGrid() {
    const grid = document.getElementById("productGrid");
    if (!grid) return;
    grid.innerHTML = "";
    products.forEach(product => grid.appendChild(createCatalogCard(product)));
}

function renderProductDetails() {
    const params = new URLSearchParams(window.location.search);
    const id = params.get("id");
    const product = getProductById(id);
    const root = document.getElementById("productDetails");
    if (!root) return;

    if (!product) {
        root.innerHTML = `
            <div class="product-not-found">
                <h1>Product Not Found</h1>
                <a href="index.html#products" class="back-products">Back to Products</a>
            </div>`;
        return;
    }

    document.title = `${product.name} | Olee ' Brownies`;
    const photos = product.images;
    let current = 0;

    root.innerHTML = `
        <div class="details-layout">
            <div class="details-gallery">
                <div class="details-main-image-wrap">
                    <img id="detailsMainImage" class="details-main-image" src="${photos[0]}" alt="${escapeHtml(product.name)}">
                    ${photos.length > 1 ? `
                        <button type="button" class="details-arrow details-prev" id="detailsPrev" aria-label="Previous photo">&#10094;</button>
                        <button type="button" class="details-arrow details-next" id="detailsNext" aria-label="Next photo">&#10095;</button>` : ""}
                </div>
                <div class="details-thumbnails" id="detailsThumbnails">
                    ${photos.map((photo, index) => `
                        <button type="button" class="details-thumb ${index === 0 ? "active" : ""}" data-index="${index}" aria-label="View photo ${index + 1}">
                            <img src="${photo}" alt="">
                        </button>`).join("")}
                </div>
            </div>

            <div class="details-info">
                <div class="details-label">BROWNIE PACKAGE</div>
                <h1>${escapeHtml(product.name)}</h1>
                <div class="details-price">${escapeHtml(product.price)}</div>
                <div class="details-divider"></div>
                <h2>PACKAGE DETAILS</h2>
                <p>${escapeHtml(product.description)}</p>
                <a class="details-order-btn" href="${product.whatsapp}" target="_blank" rel="noopener">
                    ORDER NOW ON WHATSAPP
                </a>
            </div>
        </div>`;

    const main = document.getElementById("detailsMainImage");
    const thumbs = [...document.querySelectorAll(".details-thumb")];
    const show = index => {
        current = (index + photos.length) % photos.length;
        main.src = photos[current];
        thumbs.forEach((thumb, i) => thumb.classList.toggle("active", i === current));
    };
    thumbs.forEach(thumb => thumb.addEventListener("click", () => show(Number(thumb.dataset.index))));
    const prev=document.getElementById("detailsPrev"), next=document.getElementById("detailsNext");
    if(prev) prev.addEventListener("click",()=>show(current-1));
    if(next) next.addEventListener("click",()=>show(current+1));
}

function escapeHtml(value) {
    return String(value).replace(/[&<>'"]/g, char => ({"&":"&amp;","<":"&lt;",">":"&gt;","'":"&#39;",'"':'&quot;'}[char]));
}

document.addEventListener("DOMContentLoaded", () => {
    renderProductGrid();
    renderProductDetails();
});
