function getProductById(id) {
    return products.find(product => product.id === id);
}

function createCatalogCard(product) {
    const card = document.createElement("a");
    card.className = "catalog-card";
    card.href = `product.html?id=${encodeURIComponent(product.id)}`;
    card.setAttribute("aria-label", `View ${product.name}`);

    const image = document.createElement("img");
    image.className = "catalog-card-image";
    image.src = product.images[0];
    image.alt = product.name;
    image.loading = "lazy";

    const name = document.createElement("h3");
    name.className = "catalog-card-name";
    name.textContent = product.name;

    card.append(image, name);
    return card;
}

function renderProductGrid() {
    const grid = document.getElementById("productGrid");
    if (!grid) return;
    grid.innerHTML = "";
    products.forEach(product => grid.appendChild(createCatalogCard(product)));
}

function setMetaTag(attribute, key, content) {
    let tag = document.querySelector(`meta[${attribute}="${key}"]`);
    if (!tag) {
        tag = document.createElement("meta");
        tag.setAttribute(attribute, key);
        document.head.appendChild(tag);
    }
    tag.setAttribute("content", content);
}

function updateProductSeoMetadata(product) {
    const title = product.seoTitle || `${product.name} | Olee ' Brownies`;
    const description = product.seoDescription || `${product.name} | ${product.description}`;
    const canonicalUrl = new URL(
        `product.html?id=${encodeURIComponent(product.id)}`,
        "https://asaranga-94.github.io/olee-brownies-website/"
    ).href;
    const imageUrl = new URL(product.images[0], window.location.href).href;

    document.title = title;
    setMetaTag("name", "description", description);

    // Social-sharing metadata for crawlers that read the rendered page.
    setMetaTag("property", "og:type", "product");
    setMetaTag("property", "og:title", title);
    setMetaTag("property", "og:description", description);
    setMetaTag("property", "og:url", canonicalUrl);
    setMetaTag("property", "og:image", imageUrl);
    setMetaTag("property", "og:site_name", "Olee ' Brownies");

    let canonical = document.querySelector('link[rel="canonical"]');
    if (!canonical) {
        canonical = document.createElement("link");
        canonical.rel = "canonical";
        document.head.appendChild(canonical);
    }
    canonical.href = canonicalUrl;

    const productSchema = {
        "@context": "https://schema.org",
        "@type": "Product",
        "name": product.name,
        "description": product.description,
        "image": product.images.map(image => new URL(image, window.location.href).href),
        "brand": {
            "@type": "Brand",
            "name": "Olee ' Brownies"
        },
        "url": canonicalUrl
    };

    // Add an Offer only when the catalog gives one exact fixed price.
    // Starting prices and custom prices are deliberately not converted into exact offers.
    const fixedPrice = product.price.match(/^Rs\.\s*([\d,]+)$/i);
    if (fixedPrice) {
        productSchema.offers = {
            "@type": "Offer",
            "url": canonicalUrl,
            "priceCurrency": "LKR",
            "price": fixedPrice[1].replace(/,/g, ""),
            "availability": "https://schema.org/PreOrder"
        };
    }

    let structuredData = document.getElementById("productStructuredData");
    if (!structuredData) {
        structuredData = document.createElement("script");
        structuredData.id = "productStructuredData";
        structuredData.type = "application/ld+json";
        document.head.appendChild(structuredData);
    }
    structuredData.textContent = JSON.stringify(productSchema);
}

function renderProductDetails() {
    const params = new URLSearchParams(window.location.search);
    const id = params.get("id");
    const product = getProductById(id);
    const root = document.getElementById("productDetails");
    if (!root) return;

    if (!product) {
        root.innerHTML = `
            <div class="product-not-found">
                <h1>Product Not Found</h1>
                <a href="index.html#products" class="back-products">Back to Products</a>
            </div>`;
        return;
    }

    updateProductSeoMetadata(product);
    const photos = product.images;
    let current = 0;

    root.innerHTML = `
        <div class="details-layout">
            <div class="details-gallery">
                <div class="details-main-image-wrap">
                    <img id="detailsMainImage" class="details-main-image" src="${photos[0]}" alt="${escapeHtml(product.name)}">
                    ${photos.length > 1 ? `
                        <button type="button" class="details-arrow details-prev" id="detailsPrev" aria-label="Previous photo">&#10094;</button>
                        <button type="button" class="details-arrow details-next" id="detailsNext" aria-label="Next photo">&#10095;</button>` : ""}
                </div>
                <div class="details-thumbnails" id="detailsThumbnails">
                    ${photos.map((photo, index) => `
                        <button type="button" class="details-thumb ${index === 0 ? "active" : ""}" data-index="${index}" aria-label="View photo ${index + 1}">
                            <img src="${photo}" alt="">
                        </button>`).join("")}
                </div>
            </div>

            <div class="details-info">
                <div class="details-label">BROWNIE PACKAGE</div>
                <h1>${escapeHtml(product.name)}</h1>
                <div class="details-price">${escapeHtml(product.price)}</div>
                <div class="details-divider"></div>
                <h2>PACKAGE DETAILS</h2>
                <p>${escapeHtml(product.description)}</p>
                <a class="details-order-btn" href="${product.whatsapp}" target="_blank" rel="noopener">
                    ORDER NOW ON WHATSAPP
                </a>
            </div>
        </div>`;

    const main = document.getElementById("detailsMainImage");
    const thumbs = [...document.querySelectorAll(".details-thumb")];
    const show = index => {
        current = (index + photos.length) % photos.length;
        main.src = photos[current];
        thumbs.forEach((thumb, i) => thumb.classList.toggle("active", i === current));
    };
    thumbs.forEach(thumb => thumb.addEventListener("click", () => show(Number(thumb.dataset.index))));
    const prev=document.getElementById("detailsPrev"), next=document.getElementById("detailsNext");
    if(prev) prev.addEventListener("click",()=>show(current-1));
    if(next) next.addEventListener("click",()=>show(current+1));
}

function escapeHtml(value) {
    return String(value).replace(/[&<>'"]/g, char => ({"&":"&amp;","<":"&lt;",">":"&gt;","'":"&#39;",'"':'&quot;'}[char]));
}

document.addEventListener("DOMContentLoaded", () => {
    renderProductGrid();
    renderProductDetails();
});
